-- 추가 검증은 원본 후보와 종료 판정을 변경하지 않고 요청·사건을 추가한다.
-- 실행 권한이나 대상 HTTP 송신 권한을 이 표가 부여하지 않는다.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    candidate_id bigint NOT NULL REFERENCES exploration_nodes(id) ON DELETE CASCADE,
    original_run_ref text NOT NULL CHECK (length(original_run_ref) BETWEEN 1 AND 256),
    original_evidence_version bigint NOT NULL CHECK (original_evidence_version > 0),
    original_evidence_digest text NOT NULL CHECK (original_evidence_digest ~ '^[0-9a-f]{64}$'),
    requester text NOT NULL CHECK (length(requester) BETWEEN 1 AND 128),
    request_key text NOT NULL CHECK (request_key ~ '^[A-Za-z0-9][A-Za-z0-9._-]{7,127}$'),
    method text NOT NULL CHECK (method IN ('stored/v1')),
    requested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (task_id, candidate_id, requester, request_key)
);
CREATE INDEX IF NOT EXISTS diagnostic_candidate_verification_candidate_idx
    ON diagnostic_candidate_verification_requests(task_id, candidate_id, id DESC);

-- product_api can insert requests but cannot supply a candidate from another task,
-- a non-candidate node, or a different immutable evidence version. Keep this
-- check at the storage boundary even when the API has already checked it.
CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM tasks t JOIN exploration_nodes n ON n.exploration_id=t.exploration_id
        WHERE t.id=NEW.task_id AND t.deleted_at IS NULL AND n.id=NEW.candidate_id
          AND n.kind='fact' AND n.state='confirmed' AND n.origin='e2_diagnostic_candidate_v1'
          AND n.payload->'diagnostic_candidate_v1'->>'task_id'=NEW.task_id::text
          AND n.payload->'diagnostic_candidate_v1'->>'run_ref'=NEW.original_run_ref
          AND n.payload->'diagnostic_candidate_v1'->>'evidence_digest'=NEW.original_evidence_digest
          AND n.payload->'diagnostic_candidate_v1'->>'evidence_version'=NEW.original_evidence_version::text
          AND EXISTS (SELECT 1 FROM exploration_edges e JOIN exploration_nodes src
              ON src.id=e.src_id AND src.exploration_id=n.exploration_id AND src.kind='intent'
              WHERE e.exploration_id=n.exploration_id AND e.dst_id=n.id AND e.rel='yields'
                AND src.id::text=n.payload->'diagnostic_candidate_v1'->>'intent_id')
    ) THEN
        RAISE EXCEPTION 'candidate verification binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_bind_insert ON diagnostic_candidate_verification_requests;
CREATE TRIGGER diagnostic_candidate_verification_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_requests
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_bind();

CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES diagnostic_candidate_verification_requests(id) ON DELETE CASCADE,
    step integer NOT NULL CHECK (step > 0),
    process_state text NOT NULL CHECK (process_state IN ('checking_stored_evidence','awaiting_approval','running','completed','failed','cancelled','expired')),
    verdict text CHECK (verdict IN ('confirmed','negative','insufficient','unsupported')),
    reason text NOT NULL CHECK (length(reason) BETWEEN 1 AND 128),
    sources json NOT NULL DEFAULT '[]'::json CHECK (json_typeof(sources) = 'array' AND octet_length(sources::text) <= 65536),
    sources_digest text NOT NULL CHECK (sources_digest ~ '^[0-9a-f]{64}$'),
    rule_version text NOT NULL CHECK (length(rule_version) BETWEEN 1 AND 64),
    execution_ref text NOT NULL DEFAULT '',
    approval_ref text NOT NULL DEFAULT '',
    event_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (request_id, step),
    CHECK ((process_state = 'completed' AND verdict IS NOT NULL) OR (process_state <> 'completed' AND verdict IS NULL))
);
CREATE INDEX IF NOT EXISTS diagnostic_candidate_verification_event_idx
    ON diagnostic_candidate_verification_events(request_id, step DESC);
