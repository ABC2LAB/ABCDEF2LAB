-- 추가 검증은 원본 후보와 종료 판정을 변경하지 않고 요청·사건을 추가한다.
-- 실행 권한이나 대상 HTTP 송신 권한을 이 표가 부여하지 않는다.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    candidate_id bigint NOT NULL REFERENCES exploration_nodes(id) ON DELETE CASCADE,
    original_run_ref text NOT NULL CHECK (length(original_run_ref) BETWEEN 1 AND 256),
    original_evidence_version bigint NOT NULL CHECK (original_evidence_version > 0),
    original_evidence_digest text NOT NULL CHECK (original_evidence_digest ~ '^[0-9a-f]{64}$'),
    requester text NOT NULL CHECK (length(requester) BETWEEN 1 AND 128),
    request_key text NOT NULL CHECK (request_key ~ '^[A-Za-z0-9][A-Za-z0-9._-]{7,127}$'),
    method text NOT NULL CHECK (method IN ('stored/v1','active/v1','llm/v1')),
    requested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (task_id, candidate_id, requester, request_key)
);
CREATE INDEX IF NOT EXISTS diagnostic_candidate_verification_candidate_idx
    ON diagnostic_candidate_verification_requests(task_id, candidate_id, id DESC);
ALTER TABLE diagnostic_candidate_verification_requests DROP CONSTRAINT IF EXISTS diagnostic_candidate_verification_requests_method_check;
ALTER TABLE diagnostic_candidate_verification_requests ADD CONSTRAINT diagnostic_candidate_verification_requests_method_check CHECK (method IN ('stored/v1','active/v1','llm/v1'));

-- product_api can insert requests but cannot supply a candidate from another task,
-- a non-candidate node, or a different immutable evidence version. Keep this
-- check at the storage boundary even when the API has already checked it.
CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM tasks t JOIN exploration_nodes n ON n.exploration_id=t.exploration_id
        WHERE t.id=NEW.task_id AND t.deleted_at IS NULL AND n.id=NEW.candidate_id
          AND n.kind='fact' AND n.state='confirmed' AND n.origin='e2_diagnostic_candidate_v1'
          AND n.payload->'diagnostic_candidate_v1'->>'task_id'=NEW.task_id::text
          AND n.payload->'diagnostic_candidate_v1'->>'run_ref'=NEW.original_run_ref
          AND n.payload->'diagnostic_candidate_v1'->>'evidence_digest'=NEW.original_evidence_digest
          AND n.payload->'diagnostic_candidate_v1'->>'evidence_version'=NEW.original_evidence_version::text
          AND EXISTS (SELECT 1 FROM exploration_edges e JOIN exploration_nodes src
              ON src.id=e.src_id AND src.exploration_id=n.exploration_id AND src.kind='intent'
              WHERE e.exploration_id=n.exploration_id AND e.dst_id=n.id AND e.rel='yields'
                AND src.id::text=n.payload->'diagnostic_candidate_v1'->>'intent_id')
    ) THEN
        RAISE EXCEPTION 'candidate verification binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_bind_insert ON diagnostic_candidate_verification_requests;
CREATE TRIGGER diagnostic_candidate_verification_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_requests
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_bind();

CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES diagnostic_candidate_verification_requests(id) ON DELETE CASCADE,
    step integer NOT NULL CHECK (step > 0),
    process_state text NOT NULL CHECK (process_state IN ('requested','checking_stored_evidence','awaiting_approval','approved','rejected','running','completed','failed','cancelled','expired')),
    verdict text CHECK (verdict IN ('confirmed','negative','insufficient','unsupported')),
    reason text NOT NULL CHECK (length(reason) BETWEEN 1 AND 128),
    sources json NOT NULL DEFAULT '[]'::json CHECK (json_typeof(sources) = 'array' AND octet_length(sources::text) <= 16384),
    sources_digest text NOT NULL CHECK (sources_digest ~ '^[0-9a-f]{64}$'),
    rule_version text NOT NULL CHECK (length(rule_version) BETWEEN 1 AND 64),
    execution_ref text NOT NULL DEFAULT '',
    approval_ref text NOT NULL DEFAULT '',
    event_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (request_id, step),
    CHECK ((process_state = 'completed' AND verdict IS NOT NULL) OR (process_state <> 'completed' AND verdict IS NULL))
);
CREATE INDEX IF NOT EXISTS diagnostic_candidate_verification_event_idx
    ON diagnostic_candidate_verification_events(request_id, step DESC);
ALTER TABLE diagnostic_candidate_verification_events DROP CONSTRAINT IF EXISTS diagnostic_candidate_verification_events_process_state_check;
ALTER TABLE diagnostic_candidate_verification_events ADD CONSTRAINT diagnostic_candidate_verification_events_process_state_check CHECK (process_state IN ('requested','checking_stored_evidence','awaiting_approval','approved','rejected','running','completed','failed','cancelled','expired'));

-- Finalized E² calls contribute only a bounded, non-sensitive observation
-- projection. The original trusted result and diagnosis-run remain immutable.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_observations_v2 (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    run_ref text NOT NULL CHECK (length(run_ref) BETWEEN 1 AND 256),
    call_ref text NOT NULL CHECK (length(call_ref) BETWEEN 1 AND 128),
    attempt_ref text NOT NULL CHECK (length(attempt_ref) BETWEEN 1 AND 128),
    source jsonb NOT NULL CHECK (jsonb_typeof(source) = 'object' AND octet_length(source::text) <= 4096),
    source_digest text NOT NULL CHECK (source_digest ~ '^[0-9a-f]{64}$'),
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (task_id, run_ref, call_ref),
    UNIQUE (task_id, run_ref, attempt_ref)
);
CREATE INDEX IF NOT EXISTS diagnostic_candidate_observations_task_idx
    ON diagnostic_candidate_observations_v2(task_id, run_ref, id);

-- A plan is an immutable proposal. Only a separate decision on its exact
-- digest may lead the protected runtime to create a new, bounded task.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_plans (
    request_id bigint PRIMARY KEY REFERENCES diagnostic_candidate_verification_requests(id) ON DELETE CASCADE,
    plan jsonb NOT NULL CHECK (jsonb_typeof(plan) = 'object' AND octet_length(plan::text) <= 4096),
    plan_digest text NOT NULL CHECK (plan_digest ~ '^[0-9a-f]{64}$'),
    target_id text NOT NULL CHECK (length(target_id) BETWEEN 1 AND 128),
    target_revision bigint NOT NULL CHECK (target_revision > 0),
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_decisions (
    request_id bigint PRIMARY KEY REFERENCES diagnostic_candidate_verification_plans(request_id) ON DELETE CASCADE,
    plan_digest text NOT NULL CHECK (plan_digest ~ '^[0-9a-f]{64}$'),
    decision text NOT NULL CHECK (decision IN ('approved','rejected')),
    decided_by text NOT NULL CHECK (length(decided_by) BETWEEN 1 AND 128),
    decided_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_plan_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM diagnostic_candidate_verification_requests q
        WHERE q.id=NEW.request_id AND q.method='active/v1'
          AND NEW.plan->>'version'='candidate-active/v1'
          AND NEW.plan->>'task_id'=q.task_id::text
          AND NEW.plan->>'candidate_id'=q.candidate_id::text
          AND NEW.plan->>'evidence_digest'=q.original_evidence_digest
          AND NEW.plan->>'original_run_ref'=q.original_run_ref
          AND NEW.plan->>'target_id'=NEW.target_id
          AND NEW.plan->>'target_revision'=NEW.target_revision::text
    ) THEN
        RAISE EXCEPTION 'candidate plan binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_plan_bind_insert ON diagnostic_candidate_verification_plans;
CREATE TRIGGER diagnostic_candidate_verification_plan_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_plans
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_plan_bind();

CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_decision_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM diagnostic_candidate_verification_plans p
        JOIN diagnostic_candidate_verification_requests q ON q.id=p.request_id
        WHERE p.request_id=NEW.request_id AND p.plan_digest=NEW.plan_digest
          AND p.expires_at>NEW.decided_at AND q.requester=NEW.decided_by
    ) THEN
        RAISE EXCEPTION 'candidate decision binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_decision_bind_insert ON diagnostic_candidate_verification_decisions;
CREATE TRIGGER diagnostic_candidate_verification_decision_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_decisions
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_decision_bind();

-- This is the only relation between the original candidate and a fresh E²
-- task. The runtime inserts it after checking the approved plan and before
-- issuing the task's protected policy. A reused original task is forbidden.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_executions (
    request_id bigint PRIMARY KEY REFERENCES diagnostic_candidate_verification_decisions(request_id) ON DELETE CASCADE,
    followup_task_id bigint NOT NULL UNIQUE REFERENCES tasks(id) ON DELETE RESTRICT,
    approval_event_id bigint NOT NULL UNIQUE REFERENCES diagnostic_candidate_verification_events(id) ON DELETE RESTRICT,
    plan_digest text NOT NULL CHECK (plan_digest ~ '^[0-9a-f]{64}$'),
    run_ref text NOT NULL CHECK (length(run_ref) BETWEEN 1 AND 256),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_event_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    method_name text;
BEGIN
    SELECT method INTO method_name FROM diagnostic_candidate_verification_requests WHERE id=NEW.request_id;
    IF method_name='llm/v1' THEN
        IF current_user='product_runtime' OR NEW.verdict IS NOT NULL OR NEW.execution_ref<>'' OR NEW.approval_ref<>'' OR NEW.rule_version<>'selected/llm-v1' OR
           (NEW.step=1 AND NEW.process_state<>'requested') OR
           (NEW.step=2 AND (NEW.process_state<>'cancelled' OR NOT EXISTS (
               SELECT 1 FROM diagnostic_candidate_verification_events prev
               WHERE prev.request_id=NEW.request_id AND prev.step=1 AND prev.process_state='requested'))) OR
           NEW.step NOT IN (1,2) THEN
            RAISE EXCEPTION 'selected verification request invalid' USING ERRCODE='23514';
        END IF;
    ELSIF method_name='stored/v1' THEN
        IF NEW.step<>1 OR NEW.process_state<>'completed' OR NEW.execution_ref<>'' OR NEW.approval_ref<>'' THEN
            RAISE EXCEPTION 'stored verification event invalid' USING ERRCODE='23514';
        END IF;
    ELSIF method_name='active/v1' THEN
        IF NEW.step=1 THEN
            IF NEW.process_state<>'awaiting_approval' OR NEW.verdict IS NOT NULL OR NEW.execution_ref<>'' OR NEW.approval_ref<>'' OR
               NOT EXISTS (SELECT 1 FROM diagnostic_candidate_verification_plans WHERE request_id=NEW.request_id) THEN
                RAISE EXCEPTION 'candidate approval event invalid' USING ERRCODE='23514';
            END IF;
        ELSIF NEW.step=2 THEN
            IF NEW.process_state NOT IN ('approved','rejected','expired','cancelled') OR NEW.verdict IS NOT NULL OR NEW.execution_ref<>'' OR
               NEW.process_state='approved' AND NEW.approval_ref='' OR
               NEW.process_state<>'approved' AND NEW.approval_ref<>'' OR
               NOT EXISTS (SELECT 1 FROM diagnostic_candidate_verification_events prev WHERE prev.request_id=NEW.request_id AND prev.step=1 AND prev.process_state='awaiting_approval') OR
               (NEW.process_state IN ('approved','rejected') AND NOT EXISTS (SELECT 1 FROM diagnostic_candidate_verification_decisions d
                   JOIN diagnostic_candidate_verification_plans p ON p.request_id=d.request_id AND p.plan_digest=d.plan_digest
                   WHERE d.request_id=NEW.request_id AND d.decision=NEW.process_state)) OR
               (NEW.process_state='expired' AND NOT EXISTS (SELECT 1 FROM diagnostic_candidate_verification_plans p
                   WHERE p.request_id=NEW.request_id AND p.expires_at<=NEW.event_at)) OR
               (NEW.process_state IN ('expired','cancelled') AND EXISTS (SELECT 1 FROM diagnostic_candidate_verification_decisions d WHERE d.request_id=NEW.request_id)) THEN
                RAISE EXCEPTION 'candidate decision event invalid' USING ERRCODE='23514';
            END IF;
        ELSE
            IF NEW.step NOT IN (3,4) OR
               NEW.step=3 AND NEW.process_state NOT IN ('running','failed','cancelled','expired') OR
               NEW.step=4 AND NEW.process_state NOT IN ('completed','failed','cancelled','expired') OR
               NOT EXISTS (SELECT 1 FROM diagnostic_candidate_verification_events prev WHERE prev.request_id=NEW.request_id AND prev.step=NEW.step-1
                   AND (NEW.step=3 AND prev.process_state='approved' OR NEW.step=4 AND prev.process_state='running')) OR
               NOT EXISTS (SELECT 1 FROM diagnostic_candidate_verification_decisions d WHERE d.request_id=NEW.request_id AND d.decision='approved') THEN
                RAISE EXCEPTION 'candidate execution event invalid' USING ERRCODE='23514';
            END IF;
            IF NEW.process_state IN ('running','completed') AND NOT EXISTS (
                SELECT 1 FROM diagnostic_candidate_verification_executions x WHERE x.request_id=NEW.request_id AND x.run_ref=NEW.execution_ref
            ) THEN
                RAISE EXCEPTION 'candidate execution event unbound' USING ERRCODE='23514';
            END IF;
        END IF;
        IF current_user='product_api' AND NEW.step>2 OR current_user='product_runtime' AND NEW.step<3 THEN
            RAISE EXCEPTION 'candidate event writer invalid' USING ERRCODE='42501';
        END IF;
    ELSE
        RAISE EXCEPTION 'candidate event method invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_event_bind_insert ON diagnostic_candidate_verification_events;
CREATE TRIGGER diagnostic_candidate_verification_event_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_events
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_event_bind();

CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_execution_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM diagnostic_candidate_verification_requests q
        JOIN diagnostic_candidate_verification_plans p ON p.request_id=q.id
        JOIN diagnostic_candidate_verification_decisions d ON d.request_id=q.id
        JOIN diagnostic_candidate_verification_events e ON e.id=NEW.approval_event_id AND e.request_id=q.id
        JOIN tasks t ON t.id=NEW.followup_task_id AND t.deleted_at IS NULL
        WHERE q.id=NEW.request_id AND q.method='active/v1' AND q.task_id<>NEW.followup_task_id
          AND p.plan_digest=NEW.plan_digest AND d.plan_digest=p.plan_digest AND d.decision='approved'
          AND e.process_state='approved' AND e.verdict IS NULL AND e.step=2
          AND t.paused AND NOT t.queued AND t.first_run_at IS NULL AND t.completed_at IS NULL
    ) THEN
        RAISE EXCEPTION 'candidate execution binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_execution_bind_insert ON diagnostic_candidate_verification_executions;
CREATE TRIGGER diagnostic_candidate_verification_execution_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_executions
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_execution_bind();
