-- One bounded model analysis per selected request. The immutable source
-- candidate and the sealed original run remain the authority for its context.
-- No target response body, credential, cookie or raw URL is stored here.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_analyses (
    request_id bigint PRIMARY KEY REFERENCES diagnostic_candidate_verification_requests(id) ON DELETE CASCADE,
    proposal jsonb NOT NULL CHECK (jsonb_typeof(proposal)='object' AND octet_length(proposal::text) <= 16384),
    proposal_digest text NOT NULL CHECK (proposal_digest ~ '^[0-9a-f]{64}$'),
    profile_id bigint NOT NULL CHECK (profile_id > 0),
    model_requests integer NOT NULL CHECK (model_requests = 1),
    input_tokens bigint NOT NULL CHECK (input_tokens >= 0),
    output_tokens bigint NOT NULL CHECK (output_tokens >= 0),
    cost_usd_micros bigint NOT NULL CHECK (cost_usd_micros >= 0),
    analyzed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE OR REPLACE FUNCTION diagnostic_candidate_verification_analysis_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM diagnostic_candidate_verification_requests q
        JOIN diagnostic_candidate_verification_events e ON e.request_id=q.id AND e.step=2
        WHERE q.id=NEW.request_id AND q.method='llm/v1' AND e.process_state='checking_stored_evidence'
    ) THEN
        RAISE EXCEPTION 'selected analysis binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_verification_analysis_bind_insert ON diagnostic_candidate_verification_analyses;
CREATE TRIGGER diagnostic_candidate_verification_analysis_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_analyses
FOR EACH ROW EXECUTE FUNCTION diagnostic_candidate_verification_analysis_bind();

