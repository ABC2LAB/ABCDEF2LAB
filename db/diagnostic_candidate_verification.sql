-- A business answer records a user's statement, not target execution consent.
-- The question index is bound to the immutable analyzed proposal digest.
CREATE TABLE IF NOT EXISTS diagnostic_candidate_verification_answers (
    request_id bigint NOT NULL REFERENCES diagnostic_candidate_verification_analyses(request_id) ON DELETE RESTRICT,
    question_index integer NOT NULL CHECK (question_index BETWEEN 1 AND 4),
    analysis_digest text NOT NULL CHECK (analysis_digest ~ '^[0-9a-f]{64}$'),
    question_digest text NOT NULL CHECK (question_digest ~ '^[0-9a-f]{64}$'),
    answer text NOT NULL CHECK (length(answer) BETWEEN 1 AND 4096),
    answer_digest text NOT NULL CHECK (answer_digest ~ '^[0-9a-f]{64}$'),
    answered_by text NOT NULL CHECK (length(answered_by) BETWEEN 1 AND 128),
    answered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (request_id, question_index)
);
CREATE OR REPLACE FUNCTION diagnostic_candidate_answer_bind() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM diagnostic_candidate_verification_analyses a
        JOIN diagnostic_candidate_verification_requests q ON q.id=a.request_id
        JOIN LATERAL (SELECT step,process_state FROM diagnostic_candidate_verification_events
            WHERE request_id=q.id ORDER BY step DESC LIMIT 1) e ON true
        WHERE q.id=NEW.request_id AND q.method='llm/v1' AND q.requester=NEW.answered_by
          AND a.proposal_digest=NEW.analysis_digest AND e.step=3 AND e.process_state='analysis_ready'
          AND jsonb_typeof(a.proposal->'business_questions')='array'
          AND jsonb_array_length(a.proposal->'business_questions')>=NEW.question_index
    ) THEN
        RAISE EXCEPTION 'candidate business answer binding invalid' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS diagnostic_candidate_answer_bind_insert ON diagnostic_candidate_verification_answers;
CREATE TRIGGER diagnostic_candidate_answer_bind_insert
BEFORE INSERT ON diagnostic_candidate_verification_answers
