const abortKo = (s: string) => ABORT[s] ?? s;
const hintKo = (s: string) => HINT.find(([zh]) => s.startsWith(zh))?.[1] ?? s;
/** "，已运行 3 轮 / 1m2s" 의 뒷부분 → " · 3회 / 1m2s 실행" */
const ranKo = (s: string | undefined) => (s ? ` · ${s.replace(/(\d+) 轮/g, "$1회")} 실행` : "");

const RULES: [RegExp, (m: RegExpMatchArray) => string][] = [
  [
    /^（运行被中断：(.+?)；停在(模型输出阶段|工具执行阶段|执行过程中)(?:，已运行 (.+?))?，未完成）/,
    (m) => `(실행 중단: ${abortKo(m[1])} · ${STAGE[m[2]]} 단계에서 멈춤${ranKo(m[3])} · 미완료)`,
  ],
  [
    /^（达到运行预算上限\(([^)]+)\)，已收尾写回事实(?:，已运行 (.+?))?；本次无文字总结）/,
    (m) => `(실행 한도(${m[1]})에 도달 · 찾은 사실은 저장함${ranKo(m[2])} · 요약 없음)`,
  ],
  [/^（无文字总结，终态 ([^：]+)：(.*)）$/, (m) => `(요약 없음 · 종료 상태 ${m[1]}: ${hintKo(m[2])})`],
  [/^执行出错: /, () => "실행 오류: "],
  [/^\[模型\] ?/, () => "[모델] "],
];

/** 엔진의 중국어 고정 문구를 한국어로. 해당하지 않는 문장은 그대로 돌려준다. */
export function zhToKo(text: string): string {
  for (const [re, ko] of RULES) {
    const m = text.match(re);
    if (m) return ko(m) + text.slice(m[0].length);
  }
  return text;
}
